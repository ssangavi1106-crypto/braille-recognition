import React, { useEffect, useState, useRef } from 'react';
import { Volume2, VolumeX, Download, FileText, Globe, Sliders, Settings2 } from 'lucide-react';
import { SUPPORTED_LANGUAGES } from '../lib/braille.ts';
import { getAvailableVoices, findBestVoice, generateSpeechWav, speakSentenceRobust } from '../lib/speech.ts';

interface SpeechBarProps {
  text: string;
  braille: string;
  selectedLang: string;
  onLangChange: (lang: string) => void;
  onOpenLanguageSettings?: () => void;
}

export const SpeechBar: React.FC<SpeechBarProps> = ({
  text,
  braille,
  selectedLang,
  onLangChange,
  onOpenLanguageSettings,
}) => {
  const [isPlaying, setIsPlaying] = useState(false);
  const [rate, setRate] = useState<number>(0.95);
  const [pitch, setPitch] = useState<number>(1.0);
  const [showSettings, setShowSettings] = useState(false);
  const [voices, setVoices] = useState<SpeechSynthesisVoice[]>([]);
  const utteranceRef = useRef<SpeechSynthesisUtterance | null>(null);

  useEffect(() => {
    getAvailableVoices().then(setVoices);
  }, []);

  // Stop speaking if unmounting
  useEffect(() => {
    return () => {
      if (typeof window !== 'undefined' && 'speechSynthesis' in window) {
        window.speechSynthesis.cancel();
      }
    };
  }, []);

  const handleSpeak = () => {
    if (!text || text === '—' || text === 'No words or Braille detected') {
      return;
    }

    speakSentenceRobust(
      text,
      selectedLang,
      rate,
      pitch,
      () => setIsPlaying(true),
      () => setIsPlaying(false)
    );
  };

  const handleStop = () => {
    if (typeof window !== 'undefined' && 'speechSynthesis' in window) {
      window.speechSynthesis.cancel();
      setIsPlaying(false);
    }
  };

  const handleDownloadAudio = () => {
    if (!text) return;
    const blob = generateSpeechWav(text);
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `braille_speech_${selectedLang}.wav`;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
  };

  const handleDownloadReport = () => {
    const langObj = SUPPORTED_LANGUAGES[selectedLang];
    const content = `=====================================================
BRAILLE & VOICE RECOGNITION STUDIO REPORT
=====================================================
Generated: ${new Date().toLocaleString()}
Language: ${langObj?.name || selectedLang} (${langObj?.nativeName || ''})

[RECOGNIZED SENTENCE]:
${text || '—'}

[BRAILLE NOTATION (UNICODE)]:
${braille || '—'}

=====================================================
Accurate Braille transcription generated by AI Studio.
=====================================================`;

    const blob = new Blob([content], { type: 'text/plain;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `braille_report_${Date.now()}.txt`;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
  };

  const canPlay = Boolean(text && text !== '—' && text !== 'No words or Braille detected');

  // Group languages for dropdown
  const indianLangs = Object.entries(SUPPORTED_LANGUAGES).filter(([_, info]) => info.category === 'indian');
  const popularLangs = Object.entries(SUPPORTED_LANGUAGES).filter(([_, info]) => info.category === 'popular');
  const asianLangs = Object.entries(SUPPORTED_LANGUAGES).filter(([_, info]) => info.category === 'asian');
  const europeanLangs = Object.entries(SUPPORTED_LANGUAGES).filter(([_, info]) => info.category === 'european');
  const otherLangs = Object.entries(SUPPORTED_LANGUAGES).filter(([_, info]) => info.category === 'other');

  return (
    <div className="bg-slate-900/90 border border-slate-800 rounded-xl p-4 shadow-xl">
      <div className="flex flex-wrap items-center justify-between gap-4">
        {/* Playback & Wave status */}
        <div className="flex items-center gap-3">
          {isPlaying ? (
            <button
              onClick={handleStop}
              className="flex items-center gap-2 px-5 py-2.5 rounded-xl bg-rose-600 hover:bg-rose-500 text-white font-semibold text-sm transition-all shadow-md shadow-rose-950/40 cursor-pointer"
            >
              <VolumeX className="w-4 h-4 animate-pulse" />
              <span>Stop Speaking</span>
            </button>
          ) : (
            <button
              onClick={handleSpeak}
              disabled={!canPlay}
              className="flex items-center gap-2 px-5 py-2.5 rounded-xl bg-emerald-600 hover:bg-emerald-500 disabled:opacity-40 disabled:hover:bg-emerald-600 text-white font-semibold text-sm transition-all shadow-md shadow-emerald-950/40 cursor-pointer"
            >
              <Volume2 className="w-4 h-4" />
              <span>Speak Sentence</span>
            </button>
          )}

          {/* Voice Wave Indicator */}
          {isPlaying && (
            <div className="flex items-center gap-1 h-6 px-2 py-1 bg-emerald-950/50 border border-emerald-800/40 rounded-lg">
              <span className="w-1 h-3 bg-emerald-400 rounded-full animate-bounce [animation-delay:0ms]" />
              <span className="w-1 h-5 bg-emerald-400 rounded-full animate-bounce [animation-delay:150ms]" />
              <span className="w-1 h-4 bg-emerald-400 rounded-full animate-bounce [animation-delay:300ms]" />
              <span className="w-1 h-6 bg-emerald-400 rounded-full animate-bounce [animation-delay:450ms]" />
              <span className="w-1 h-2 bg-emerald-400 rounded-full animate-bounce [animation-delay:200ms]" />
              <span className="text-[11px] font-medium text-emerald-300 ml-1">Speaking Voice</span>
            </div>
          )}
        </div>

        {/* Language & Voice Controls */}
        <div className="flex items-center gap-2 flex-wrap">
          {/* Quick Language Select */}
          <div className="flex items-center gap-1.5 bg-slate-950 px-3 py-1.5 rounded-lg border border-slate-800 max-w-[260px]">
            <Globe className="w-3.5 h-3.5 text-slate-400 shrink-0" />
            <select
              value={selectedLang}
              onChange={(e) => {
                if (e.target.value === '__modal__') {
                  onOpenLanguageSettings?.();
                } else {
                  onLangChange(e.target.value);
                }
              }}
              className="bg-transparent text-xs font-medium text-slate-200 outline-none cursor-pointer truncate w-full"
            >
              <optgroup label="🇮🇳 Indian Languages (தமிழ், हिन्दी...)">
                {indianLangs.map(([code, item]) => (
                  <option key={code} value={code} className="bg-slate-900 text-white">
                    {item.flag} {item.name} ({item.nativeName})
                  </option>
                ))}
              </optgroup>
              <optgroup label="Popular Global">
                {popularLangs.map(([code, item]) => (
                  <option key={code} value={code} className="bg-slate-900 text-white">
                    {item.flag} {item.name} ({item.nativeName})
                  </option>
                ))}
              </optgroup>
              <optgroup label="Asian Languages">
                {asianLangs.map(([code, item]) => (
                  <option key={code} value={code} className="bg-slate-900 text-white">
                    {item.flag} {item.name} ({item.nativeName})
                  </option>
                ))}
              </optgroup>
              <optgroup label="European Languages">
                {europeanLangs.map(([code, item]) => (
                  <option key={code} value={code} className="bg-slate-900 text-white">
                    {item.flag} {item.name} ({item.nativeName})
                  </option>
                ))}
              </optgroup>
              <optgroup label="Middle Eastern & African">
                {otherLangs.map(([code, item]) => (
                  <option key={code} value={code} className="bg-slate-900 text-white">
                    {item.flag} {item.name} ({item.nativeName})
                  </option>
                ))}
              </optgroup>
            </select>
          </div>

          {/* All Languages Modal Button */}
          <button
            onClick={onOpenLanguageSettings}
            className="flex items-center gap-1.5 px-3 py-2 text-xs font-medium rounded-lg bg-indigo-600/30 hover:bg-indigo-600/50 text-indigo-300 hover:text-white transition-colors border border-indigo-500/40 cursor-pointer"
            title="Open Complete All Languages Catalog (75+)"
          >
            <Settings2 className="w-3.5 h-3.5" />
            <span className="hidden sm:inline">All Languages (75+)</span>
          </button>

          <button
            onClick={() => setShowSettings(!showSettings)}
            className={`p-2 rounded-lg border transition-colors cursor-pointer ${
              showSettings
                ? 'bg-indigo-600 border-indigo-500 text-white'
                : 'bg-slate-800 border-slate-700 text-slate-300 hover:text-white'
            }`}
            title="Speech Speed & Pitch Settings"
          >
            <Sliders className="w-4 h-4" />
          </button>

          <button
            onClick={handleDownloadAudio}
            disabled={!canPlay}
            className="flex items-center gap-1.5 px-3 py-2 text-xs font-medium rounded-lg bg-slate-800 hover:bg-slate-700 text-slate-300 hover:text-white disabled:opacity-40 transition-colors border border-slate-700 cursor-pointer"
            title="Download Speech Audio"
          >
            <Download className="w-3.5 h-3.5" />
            <span className="hidden sm:inline">Audio</span>
          </button>

          <button
            onClick={handleDownloadReport}
            disabled={!canPlay}
            className="flex items-center gap-1.5 px-3 py-2 text-xs font-medium rounded-lg bg-slate-800 hover:bg-slate-700 text-slate-300 hover:text-white disabled:opacity-40 transition-colors border border-slate-700 cursor-pointer"
            title="Download Full Text & Braille Report"
          >
            <FileText className="w-3.5 h-3.5" />
            <span className="hidden sm:inline">Report</span>
          </button>
        </div>
      </div>

      {/* Voice Sliders Drawer */}
      {showSettings && (
        <div className="grid grid-cols-1 sm:grid-cols-2 gap-4 mt-3 pt-3 border-t border-slate-800/80">
          <div>
            <div className="flex justify-between text-xs text-slate-400 mb-1">
              <span>Speech Speed:</span>
              <span className="font-mono text-slate-200">{rate.toFixed(2)}x</span>
            </div>
            <input
              type="range"
              min="0.5"
              max="1.5"
              step="0.05"
              value={rate}
              onChange={(e) => setRate(parseFloat(e.target.value))}
              className="w-full accent-indigo-500 cursor-pointer"
            />
          </div>
          <div>
            <div className="flex justify-between text-xs text-slate-400 mb-1">
              <span>Voice Pitch:</span>
              <span className="font-mono text-slate-200">{pitch.toFixed(1)}</span>
            </div>
            <input
              type="range"
              min="0.5"
              max="1.5"
              step="0.1"
              value={pitch}
              onChange={(e) => setPitch(parseFloat(e.target.value))}
              className="w-full accent-indigo-500 cursor-pointer"
            />
          </div>
        </div>
      )}
    </div>
  );
};
